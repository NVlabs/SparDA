def discover_scan_roots(repo_root: Path, accuracy_root: Path, efficiency_root: Path) -> list[Path]:
    scan_roots: list[Path] = []
    for candidate in (accuracy_root, efficiency_root):
        if candidate.exists():
            scan_roots.append(candidate)
    if not scan_roots:
        scan_roots.append(repo_root)
    else:
        if repo_root not in scan_roots:
            scan_roots.append(repo_root)
    unique: list[Path] = []
    seen: set[Path] = set()
    for root in scan_roots:
        resolved = root.resolve()
        if resolved not in seen:
            unique.append(resolved)
            seen.add(resolved)
    return unique


def is_benchmark_generated_data_dir(path: Path) -> bool:
    parts = path.parts
    for idx in range(len(parts) - 5):
        if (
            parts[idx] == "NOSA"
            and parts[idx + 1] == "benchmarks"
            and parts[idx + 2] == "RULER"
            and parts[idx + 3] == "scripts"
            and parts[idx + 4] == "results"
            and parts[idx + 5] == "data"
        ):
            return True
    return False


def scan_candidates(scan_roots: Iterable[Path]) -> dict[str, set[Path]]:
    out: dict[str, set[Path]] = {
        "helmet_files": set(),
        "helmet_hr": set(),
        "longbench_results": set(),
        "ruler_summaries": set(),
        "reasoning_logs": set(),
        "efficiency_summaries": set(),
        "block_stats": set(),
    }
    for root in scan_roots:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_SCAN_DIRS]
            dir_path = Path(dirpath)
            if is_benchmark_generated_data_dir(dir_path):
                dirnames[:] = []
                continue
            parts = set(dir_path.parts)
            for filename in filenames:
                path = dir_path / filename
                if "helmet" in parts:
                    if filename == "block_hit_rate_summary.json":
                        out["helmet_hr"].add(path.resolve())
                    if (
                        filename != "block_hit_rate_summary.json"
                        and not HELMET_SHARD_JSON_RE.search(filename)
                        and (
                        filename.endswith(".score.stat")
                        or filename.endswith(".score")
                        or filename.endswith("-gpt4eval_o.json")
                        or filename.endswith(".json")
                        )
                    ):
                        out["helmet_files"].add(path.resolve())
                if filename == "result.json" and ("pred" in parts or "pred_e" in parts):
                    if "longbench" in parts or "LongBench" in parts:
                        out["longbench_results"].add(path.resolve())
                if filename == "summary.csv" and "pred" in parts:
                    if "ruler" in parts or "RULER" in parts:
                        out["ruler_summaries"].add(path.resolve())
                if filename == "result.log" and ("reasoning" in parts or "Reasoning" in parts):
                    out["reasoning_logs"].add(path.resolve())
                if filename == "summary.tsv" and "efficiency" in parts:
                    out["efficiency_summaries"].add(path.resolve())
                if filename.endswith("_block_stats.json") or filename == "block_hit_rate_stats.json":
                    if (
                        "longbench" in parts
                        or "LongBench" in parts
                        or "ruler" in parts
                        or "RULER" in parts
                        or "reasoning" in parts
                        or "Reasoning" in parts
                    ):
                        out["block_stats"].add(path.resolve())
    return out


def build_helmet_groups(paths: Iterable[Path]) -> dict[tuple[str, str, str], set[Path]]:
    groups: dict[tuple[str, str, str], set[Path]] = defaultdict(set)
    for path in paths:
        parts = path.parts
        if "helmet" not in parts:
            continue
        config, model_dir, model_key_idx = parse_benchmark_path_layout(parts, "helmet")
        if model_key_idx < 0 or len(parts) <= model_key_idx:
            continue
        model_key = parts[model_key_idx]
        groups[(config, model_dir, model_key)].add(path)
    return groups


def helmet_dataset_from_filename(name: str) -> str:
    for suffix in (".json.score.stat", ".json.score", ".json"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
            break
    if name.endswith("-gpt4eval_o"):
        name = name[: -len("-gpt4eval_o")]
    if "_seed" in name:
        name = name[: name.rindex("_seed")]
    return name.split("_eval_")[0] if "_eval_" in name else name


def is_helmet_final_json(path: Path) -> bool:
    if not path.name.endswith(".json"):
        return False
    if path.name.endswith("-gpt4eval_o.json"):
        return True
    return HELMET_SHARD_JSON_RE.search(path.name) is None


def add_helmet_metric(
    metric_store: dict[tuple[str, str], dict[str, dict[str, Any]]],
    category_dir: str,
    dataset: str,
    metric: str,
    value: float,
    source_type: str,
    source_file: Path,
    std: float | None = None,
    raw_values: list[Any] | None = None,
) -> None:
    key = (category_dir, dataset)
    entry = metric_store.setdefault(key, {})
    current = entry.get(metric)
    priority = {"stat": 4, "score": 3, "gpt4": 2, "json": 1, "summary": 0}
    if current is not None and priority.get(current["source_type"], -1) > priority.get(source_type, -1):
        return
    entry[metric] = {
        "value": value,
        "std": std,
        "raw_values": raw_values,
        "source_type": source_type,
        "source_file": str(source_file),
        "source_mtime_utc": path_mtime_utc(source_file),
    }


