def helmet_dataset_prefix(dataset: str) -> str | None:
    best = None
    for prefix in HELMET_PRIMARY_METRICS:
        if dataset == prefix or dataset.startswith(prefix + "_"):
            if best is None or len(prefix) > len(best):
                best = prefix
    return best


def helmet_is_primary_metric(dataset: str, metric: str) -> bool:
    if metric == "block_hit_rate":
        return True
    prefix = helmet_dataset_prefix(dataset)
    if prefix is None:
        return False
    targets = HELMET_PRIMARY_METRICS[prefix]
    if metric in targets:
        return True
    if "gpt-score" in targets and "gpt-" in metric and metric.endswith("-score"):
        return True
    if "gpt-f1" in targets and "gpt-" in metric and metric.endswith("-f1"):
        return True
    return False


