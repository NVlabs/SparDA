def parse_efficiency_log(log_path: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    text = log_path.read_text() if log_path.is_file() else ""
    meta = parse_kv_file(log_path) if log_path.is_file() else {}

    run_metrics: dict[str, Any] = {}
    components: list[dict[str, Any]] = []

    m = EFF_PREFILL_RE.search(text)
    if m:
        run_metrics["prefill_tokens"] = int(m.group(1))
        run_metrics["prefill_time_s"] = float(m.group(2))
    m = EFF_DECODE_RE.search(text)
    if m:
        run_metrics["decode_tokens"] = int(m.group(1))
        run_metrics["decode_time_s"] = float(m.group(2))
    m = EFF_PREFILL_THR_RE.search(text)
    if m:
        run_metrics["prefill_tokens_per_s"] = float(m.group(1))
        run_metrics["prefill_avg_runs"] = int(m.group(2))
    m = EFF_THR_RE.search(text)
    if m:
        run_metrics["decode_tokens_per_s"] = float(m.group(1))
        run_metrics["tokens_per_s"] = float(m.group(1))
        run_metrics["decode_avg_runs"] = int(m.group(2))
        run_metrics["avg_runs"] = int(m.group(2))

    m = re.search(r"Block hit-rate:\s+([0-9]+(?:\.[0-9]+)?)%", text)
    if m:
        run_metrics["block_hit_rate_pct"] = float(m.group(1))
    m = re.search(r"H2D bytes/iter:\s+([0-9.,]+)\s+MB", text)
    if m:
        run_metrics["h2d_bytes_iter_mb"] = to_float(m.group(1))
    m = re.search(r"H2D bytes/step:\s+([0-9.,]+)\s+KB", text)
    if m:
        run_metrics["h2d_bytes_step_kb"] = to_float(m.group(1))
    m = re.search(r"Est\. PCIe throughput:\s+([0-9]+(?:\.[0-9]+)?)\s+GB/s", text)
    if m:
        run_metrics["pcie_throughput_gbps"] = float(m.group(1))
    m = re.search(r"Total H2D \(prefetch stream\):\s+([0-9]+(?:\.[0-9]+)?)\s+ms", text)
    if m:
        run_metrics["h2d_total_ms"] = float(m.group(1))
    m = re.search(r"Exposed\s+\(main stream wait\):\s+([0-9]+(?:\.[0-9]+)?)\s+ms", text)
    if m:
        run_metrics["h2d_exposed_ms"] = float(m.group(1))
    m = re.search(r"Hidden\s+\(overlapped\):\s+([0-9]+(?:\.[0-9]+)?)\s+ms\s+\(([0-9]+)% overlap\)", text)
    if m:
        run_metrics["h2d_hidden_ms"] = float(m.group(1))
        run_metrics["h2d_overlap_pct"] = float(m.group(2))

    current_phase = "decode"
    for line in text.splitlines():
        title_match = EFF_BREAKDOWN_TITLE_RE.search(line)
        if title_match:
            title = title_match.group(1).strip().lower()
            if "_prefill" in title:
                current_phase = "prefill"
            elif "_decode" in title:
                current_phase = "decode"
            else:
                current_phase = "decode"
            continue

        match = EFF_COMPONENT_RE.match(line)
        if not match:
            continue
        component = match.group("component").strip()
        row = {
            "phase": current_phase,
            "component": component,
            "calls": int(match.group("calls")),
            "total_ms": float(match.group("total_ms")),
            "avg_us": float(match.group("avg_us")),
            "fraction_pct": float(match.group("fraction")),
            "est_ms": to_float(match.group("est_ms")),
            "est_avg_us": to_float(match.group("est_avg_us")),
        }
        components.append(row)
        if component == "TOTAL":
            run_metrics[f"{current_phase}_profile_total_ms"] = row["total_ms"]
            run_metrics[f"{current_phase}_profile_est_total_ms"] = row["est_ms"]
            if current_phase == "decode":
                run_metrics["profile_total_ms"] = row["total_ms"]
                run_metrics["profile_est_total_ms"] = row["est_ms"]

    run_metrics.update(
        {
            "log_model_path": meta.get("model_path", ""),
            "log_indexer_path": meta.get("indexer_path", ""),
            "log_note": meta.get("note", ""),
            "started_utc": meta.get("time_utc", ""),
            "finished_utc": meta.get("finished_utc", ""),
        }
    )
    return run_metrics, components


