def parse_benchmark_path_layout(parts: tuple[str, ...] | list[str], benchmark: str) -> tuple[str, str, int]:
    if benchmark not in parts:
        return "", "", -1
    idx = parts.index(benchmark)
    config = ""
    model_dir = ""
    next_idx = idx + 1
    first = parts[idx + 1] if len(parts) > idx + 1 else ""
    second = parts[idx + 2] if len(parts) > idx + 2 else ""

    if first in KNOWN_MODEL_DIRS and second in KNOWN_CONFIGS:
        model_dir = first
        config = second
        next_idx = idx + 3
    elif first in KNOWN_CONFIGS:
        config = first
        next_idx = idx + 2
        if second in KNOWN_MODEL_DIRS:
            model_dir = second
            next_idx = idx + 3
    elif first in KNOWN_MODEL_DIRS:
        model_dir = first
        next_idx = idx + 2

    return config, model_dir, next_idx


def parse_len_text(value: Any) -> tuple[int | None, str]:
    if value is None:
        return None, ""
    text = str(value).strip()
    if not text:
        return None, ""
    upper = text.upper()
    if upper.endswith("K"):
        num = to_int(upper[:-1])
        return (num * 1024 if num is not None else None), upper
    num = to_int(text)
    if num is None:
        return None, text
    if num % 1024 == 0 and num >= 1024:
        return num, f"{num // 1024}K"
    return num, str(num)


def parse_helmet_model_key(model_key: str) -> tuple[str, str, int | None, str]:
    m = re.search(r"_([0-9]+)k$", model_key, re.IGNORECASE)
    seq_tokens = None
    seq_label = ""
    core = model_key
    if m:
        seq_tokens = int(m.group(1)) * 1024
        seq_label = f"{m.group(1)}K"
        core = model_key[: m.start()]
    return infer_model_family(core), infer_mode(core), seq_tokens, seq_label


