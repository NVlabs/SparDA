def parse_csv_list(value: str | None) -> list[str]:
    if value is None:
        return []
    return [item.strip() for item in value.split(",") if item.strip()]


def load_default_efficiency_var(repo_root: Path, name: str, fallback: list[str]) -> list[str]:
    script_path = repo_root / "eval" / "run_efficiency.sh"
    try:
        text = script_path.read_text()
    except Exception:
        return list(fallback)

    match = re.search(rf'^\s*{re.escape(name)}="([^"]*)"', text, re.M)
    if not match:
        return list(fallback)

    configs = parse_csv_list(match.group(1))
    return configs if configs else list(fallback)


