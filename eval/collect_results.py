def parse_generic_block_context(path: Path) -> dict[str, Any]:
    parts = path.parts
    context = {
        "benchmark": "",
        "config": "",
        "model_dir": "",
        "dataset_or_task": "",
        "model_key": "",
        "model_family": "",
        "mode": "",
        "seq_len_tokens": None,
        "seq_len_label": "",
        "source_file": str(path),
    }

    if "longbench" in parts or "LongBench" in parts:
        context["benchmark"] = "longbench"
        stem = path.name.removesuffix("_block_stats.json")
        context["dataset_or_task"] = stem
        if "pred" in parts:
            pred_idx = parts.index("pred")
        else:
            pred_idx = parts.index("pred_e") if "pred_e" in parts else -1
        if pred_idx >= 0 and pred_idx + 1 < len(parts):
            context["model_key"] = parts[pred_idx + 1]
            context["model_family"] = infer_model_family(context["model_key"])
            context["mode"] = infer_mode(context["model_key"])
        if "longbench" in parts:
            context["config"], context["model_dir"], _ = parse_benchmark_path_layout(parts, "longbench")
        return context

    if "ruler" in parts or "RULER" in parts:
        context["benchmark"] = "ruler"
        context["dataset_or_task"] = path.name.removesuffix("_block_stats.json")
        if "pred" in parts:
            pred_idx = parts.index("pred")
            if pred_idx >= 3 and parts[pred_idx - 2] == "synthetic":
                context["mode"] = parts[pred_idx - 3]
                context["model_family"] = infer_model_family(context["mode"])
                seq_tokens, seq_label = parse_len_text(parts[pred_idx - 1])
                context["seq_len_tokens"] = seq_tokens
                context["seq_len_label"] = seq_label
        if "ruler" in parts:
            context["config"], context["model_dir"], _ = parse_benchmark_path_layout(parts, "ruler")
        return context

    if "reasoning" in parts or "Reasoning" in parts:
        context["benchmark"] = "reasoning"
        context["dataset_or_task"] = path.parent.parent.name if path.name == "block_hit_rate_stats.json" else path.parent.name
        context["model_key"] = path.parent.name
        context["model_family"] = infer_model_family(context["model_key"])
        context["mode"] = infer_mode(context["model_key"])
        if "reasoning" in parts:
            context["config"], context["model_dir"], _ = parse_benchmark_path_layout(parts, "reasoning")
        return context

    return context


def mark_sparse_alias_rows(rows: list[dict[str, Any]], benchmark: str) -> None:
    if benchmark == "longbench":
        sparse_values: dict[tuple[Any, ...], Any] = {}
        alias_groups: dict[tuple[Any, ...], list[tuple[int, tuple[Any, ...], Any]]] = defaultdict(list)
        for idx, row in enumerate(rows):
            if row.get("model_family") != "nosa":
                continue
            key = (
                row.get("model_dir", ""),
                row.get("variant", ""),
                row.get("max_length_tokens"),
                row.get("dataset", ""),
                row.get("bucket", ""),
                row.get("metric", ""),
            )
            if row.get("config") == "sparse":
                sparse_values[key] = row.get("value")
            elif row.get("config") == "infinigen":
                group_key = (
                    row.get("model_dir", ""),
                    row.get("variant", ""),
                    row.get("max_length_tokens"),
                )
                alias_groups[group_key].append((idx, key, row.get("value")))
    elif benchmark == "ruler":
        sparse_values = {}
        alias_groups = defaultdict(list)
        for idx, row in enumerate(rows):
            if row.get("model_family") != "nosa":
                continue
            key = (
                row.get("model_dir", ""),
                row.get("seq_len_tokens"),
                row.get("row_type", ""),
                row.get("task", ""),
            )
            if row.get("config") == "sparse":
                sparse_values[key] = row.get("score")
            elif row.get("config") == "infinigen":
                group_key = (
                    row.get("model_dir", ""),
                    row.get("seq_len_tokens"),
                )
                alias_groups[group_key].append((idx, key, row.get("score"), row.get("row_type", "")))
    else:
        return

    note = "Matches sparse output exactly; likely collected before the NOSA InfiniGen HF wrapper fix."
    for items in alias_groups.values():
        if benchmark == "ruler":
            task_items = [item for item in items if item[3] == "task"]
            if len(task_items) < 5:
                continue
            if not all(key in sparse_values and same_numeric_value(value, sparse_values[key]) for _, key, value, _ in task_items):
                continue
            matched_items = [item for item in items if item[1] in sparse_values and same_numeric_value(item[2], sparse_values[item[1]])]
            for idx, _, _, _ in matched_items:
                rows[idx]["result_status"] = "suspect_sparse_alias"
                rows[idx]["result_notes"] = note
            continue
        if len(items) < 5:
            continue
        if all(key in sparse_values and same_numeric_value(value, sparse_values[key]) for _, key, value in items):
            for idx, _, _ in items:
                rows[idx]["result_status"] = "suspect_sparse_alias"
                rows[idx]["result_notes"] = note


def collect_block_rows(paths: Iterable[Path]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    summary_rows: list[dict[str, Any]] = []
    layer_rows: list[dict[str, Any]] = []
    for path in sorted(paths):
        data = load_json(path)
        if not isinstance(data, dict):
            continue
        context = parse_generic_block_context(path)
        hit_rate = to_float(data.get("hit_rate"))
        if hit_rate is not None and hit_rate <= 1.0:
            hit_rate *= 100.0
        summary_rows.append(
            {
                **context,
                "hit_rate_pct": hit_rate,
                "miss_blocks": to_int(data.get("miss_blocks")),
                "total_blocks": to_int(data.get("total_blocks")),
                "num_layers": to_int(data.get("num_layers")),
            }
        )
        for idx, layer in enumerate(data.get("per_layer", []) or []):
            layer_hit_rate = to_float(layer.get("hit_rate"))
            if layer_hit_rate is not None and layer_hit_rate <= 1.0:
                layer_hit_rate *= 100.0
            layer_rows.append(
                {
                    **context,
                    "layer_idx": idx,
                    "layer_hit_rate_pct": layer_hit_rate,
                    "layer_miss_blocks": to_int(layer.get("miss_blocks")),
                    "layer_total_blocks": to_int(layer.get("total_blocks")),
                    "steps": to_int(layer.get("steps")),
                }
            )
    return summary_rows, layer_rows


def sort_rows(rows: list[dict[str, Any]], keys: list[str]) -> list[dict[str, Any]]:
    def normalize(value: Any) -> tuple[int, Any]:
        if value is None or value == "":
            return (2, "")
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            if isinstance(value, float) and (math.isnan(value) or math.isinf(value)):
                return (2, "")
            return (0, float(value))
        return (1, str(value))

    def key_fn(row: dict[str, Any]) -> tuple[Any, ...]:
        out = []
        for key in keys:
            out.append(normalize(row.get(key)))
        return tuple(out)

    return sorted(rows, key=key_fn)


def mean_value(values: Iterable[Any]) -> float | None:
    numbers = [to_float(value) for value in values]
    clean = [value for value in numbers if value is not None]
    if not clean:
        return None
    return sum(clean) / len(clean)


def as_percent(value: Any) -> float | None:
    num = to_float(value)
    if num is None:
        return None
    if 0.0 <= num <= 1.0 + 1e-12:
        return num * 100.0
    return num


def latest_rows_by_keys(rows: Iterable[dict[str, Any]], key_fields: list[str]) -> list[dict[str, Any]]:
    latest: dict[tuple[Any, ...], tuple[tuple[str, str], dict[str, Any]]] = {}
    for row in rows:
        key = tuple(row.get(field, "") for field in key_fields)
        stamp = str(
            row.get("source_mtime_utc")
            or row.get("finished_utc")
            or row.get("started_utc")
            or ""
        )
        source = str(
            row.get("source_file")
            or row.get("result_log")
            or row.get("model_output_dir")
            or ""
        )
        candidate = ((stamp, source), row)
        current = latest.get(key)
        if current is None or candidate[0] >= current[0]:
            latest[key] = candidate
    return [row for _, row in latest.values()]


def display_model_name(*parts: Any) -> str:
    text = " ".join(str(part or "") for part in parts).strip()
    lower = text.lower()
    for key, label in MODEL_DISPLAY_OVERRIDES.items():
        if key in lower:
            return label
    if text:
        return text
    return ""


def display_method_name(config: Any) -> str:
    text = str(config or "").strip()
    if not text:
        return ""
    match = SPARDA_CTAS_RE.fullmatch(text)
    if match:
        return f"SparDA ({int(match.group(1))} CTAs)"
    return CONFIG_LABELS.get(text, text)


def model_sort_key(model: Any) -> tuple[int, str]:
    text = str(model or "")
    lower = text.lower()
    if "nosa" in lower:
        return (0, lower)
    if "minicpm" in lower:
        return (1, lower)
    return (2, lower)


def compact_row_sort_key(row: dict[str, Any]) -> tuple[Any, ...]:
    return (
        model_sort_key(row.get("Model")),
        config_sort_key(next((cfg for cfg, label in CONFIG_LABELS.items() if label == row.get("Method")), row.get("Method"))),
        str(row.get("Context") or ""),
    )


def ordered_datasets(
    rows: Iterable[dict[str, Any]],
    *,
    category_field: str = "category",
    dataset_field: str = "dataset",
    category_order: list[str],
) -> list[str]:
    grouped: dict[str, set[str]] = defaultdict(set)
    extras: set[str] = set()
    for row in rows:
        dataset = str(row.get(dataset_field) or "")
        if not dataset:
            continue
        category = str(row.get(category_field) or "")
        if category in category_order:
            grouped[category].add(dataset)
        else:
            extras.add(dataset)
    ordered: list[str] = []
    for category in category_order:
        ordered.extend(sorted(grouped.get(category, set())))
    ordered.extend(sorted(extras - set(ordered)))
    return ordered


