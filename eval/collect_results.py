def compute_reasoning_accuracy(model_dir: Path, dataset: str, utils_module: Any | None) -> tuple[int, int, float | None]:
    files = sorted(model_dir.glob("*.jsonl"))
    data: list[dict[str, Any]] = []
    for file_path in files:
        with file_path.open() as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    data.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    if not data or utils_module is None:
        return 0, len(data), None

    correct = 0
    is_aime = dataset.startswith("aime")
    for entry in data:
        raw_generation = entry.get("generation", "")
        stripped_generation = utils_module.strip_thinking_blocks(raw_generation)
        ground_truth = utils_module.normalize_math_answer(str(entry.get("answer", "")))
        boxed = utils_module.extract_last_boxed(stripped_generation)
        if boxed is None:
            boxed = utils_module.extract_last_boxed(raw_generation)
        if boxed is not None:
            pred = utils_module.normalize_math_answer(boxed)
        elif is_aime:
            pred = utils_module.parse_aime_prediction(stripped_generation)
        else:
            pred = utils_module.parse_math_prediction(stripped_generation)
        if utils_module.normalize_math_answer(pred) == ground_truth:
            correct += 1
    total = len(data)
    accuracy = (correct / total) if total else None
    return correct, total, accuracy


def parse_reasoning_log_metrics(log_path: Path) -> dict[str, Any]:
    if not log_path.exists():
        return {
            "exact_correct": None,
            "exact_total": None,
            "exact_accuracy": None,
            "judge_model": "",
            "judge_correct": None,
            "judge_total": None,
            "judge_accuracy": None,
            "judge_status": "not_run",
            "judge_notes": "",
        }

    text = log_path.read_text()
    exact_matches = re.findall(
        r"(?:integer match|boxed exact match)\s+accuracy:\s*([0-9]+(?:\.[0-9]+)?)\s*\((\d+)\s*/\s*(\d+)\)",
        text,
        flags=re.IGNORECASE,
    )
    judge_matches = re.findall(
        r"judge\s+accuracy(?:\s*\[([^\]]+)\])?:\s*([0-9]+(?:\.[0-9]+)?)\s*\((\d+)\s*/\s*(\d+)\)",
        text,
        flags=re.IGNORECASE,
    )
    judge_skips = re.findall(
        r"judge\s+accuracy(?:\s*\[([^\]]+)\])?:\s*skipped\s*\(([^)]+)\)",
        text,
        flags=re.IGNORECASE,
    )

    exact_correct = None
    exact_total = None
    exact_accuracy = None
    if exact_matches:
        acc_text, correct_text, total_text = exact_matches[-1]
        exact_correct = int(correct_text)
        exact_total = int(total_text)
        exact_accuracy = float(acc_text)

    judge_model = ""
    judge_correct = None
    judge_total = None
    judge_accuracy = None
    judge_status = "not_run"
    judge_notes = ""
    if judge_matches:
        judge_model_text, acc_text, correct_text, total_text = judge_matches[-1]
        judge_model = judge_model_text or ""
        judge_correct = int(correct_text)
        judge_total = int(total_text)
        judge_accuracy = float(acc_text)
        judge_status = "valid"
    elif judge_skips:
        judge_model_text, judge_note_text = judge_skips[-1]
        judge_model = judge_model_text or ""
        judge_status = "skipped"
        judge_notes = judge_note_text

    return {
        "exact_correct": exact_correct,
        "exact_total": exact_total,
        "exact_accuracy": exact_accuracy,
        "judge_model": judge_model,
        "judge_correct": judge_correct,
        "judge_total": judge_total,
        "judge_accuracy": judge_accuracy,
        "judge_status": judge_status,
        "judge_notes": judge_notes,
    }


